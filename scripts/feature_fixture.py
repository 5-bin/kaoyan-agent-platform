def fifo_misses(refs, capacity):
    frames, misses = deque(), 0
    for page in refs:
        if page not in frames:
            misses += 1
            if len(frames) == capacity:
                frames.popleft()
            frames.append(page)
    return misses


def lru_misses(refs, capacity):
    frames, misses = [], 0
    for page in refs:
        if page in frames:
            frames.remove(page)
        else:
            misses += 1
            if len(frames) == capacity:
                frames.pop(0)
        frames.append(page)
    return misses


def oracle(kind, p):
    """Restricted mathematical checks; no eval or executable fixture content."""
    if kind == 'product': return math.prod(p)
    if kind == 'sum': return sum(p)
    if kind == 'power': return p[0] ** p[1]
    if kind == 'ceil_div': return (p[0] + p[1] - 1) // p[1]
    if kind == 'sub': return p[0] - p[1]
    if kind == 'div': return p[0] / p[1]
    if kind == 'bits': return int(p[0], p[1])
    if kind == 'signed': return p[0] - 2 ** p[1] if p[0] >= 2 ** (p[1]-1) else p[0]
    if kind == 'edges': return sum(1 for i in range(p[0]) for j in range(i+1,p[0]))
    if kind == 'tree_leaves': return (p[0] + 1) // 2
    if kind == 'tree_depth': return p[0].bit_length()
    if kind == 'queue': return (p[1] - p[0] + p[2]) % p[2]
    if kind == 'huffman':
        import heapq
        heap = list(p); heapq.heapify(heap); cost = 0
        while len(heap)>1:
            w = heapq.heappop(heap) + heapq.heappop(heap); cost += w; heapq.heappush(heap,w)
        return cost
    if kind == 'inversions': return sum(p[i]>p[j] for i in range(len(p)) for j in range(i+1,len(p)))
    if kind == 'fifo': return fifo_misses(p[0],p[1])
    if kind == 'lru': return lru_misses(p[0],p[1])
    if kind == 'fcfs_wait': return sum(sum(p[:i]) for i in range(len(p)))
    if kind == 'sjf_turn':
        elapsed, total = 0, 0
        for t in sorted(p): elapsed += t; total += elapsed
        return total
    if kind == 'page_address': return p[0]*p[1]+p[2]
    if kind == 'eat': return p[0]*p[1]+(1-p[0])*p[2]
    if kind == 'speedup': return 1/((1-p[0])+p[0]/p[1])
    if kind == 'pipeline': return p[0]+p[1]-1
    if kind == 'binary_search':
        n, count = p[0], 0
        while n: count += 1; n //= 2
        return count
    if kind == 'shortest':
        dist=[float('inf')]*p[0];dist[0]=0
        for _ in range(p[0]-1):
            for a,b,w in p[1]: dist[b]=min(dist[b],dist[a]+w)
        return dist[-1]
    if kind == 'hosts': return 2**(32-p[0])-2
    if kind == 'serialization': return p[0]*8/p[1]
    if kind == 'fragment_offset': return p[0]//8
    if kind == 'link_pipeline': return (p[0]+p[1]-1)*p[2]
    raise ValueError('Unknown verification kind: '+kind)

