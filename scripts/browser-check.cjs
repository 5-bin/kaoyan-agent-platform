"use strict";
// 实际后端页面检查；只使用隔离浏览器上下文和自动创建的测试账号。
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { chromium } = require("playwright");

async function main() {
  const base = process.argv[2], output = process.argv[3];
  if (!base || !output) throw new Error("用法：node scripts/browser-check.cjs http://127.0.0.1:端口 新报告.json");
  const url = new URL(base);
  if (!['127.0.0.1', 'localhost'].includes(url.hostname)) throw new Error("只检查已授权的本机测试服务");
  const screenshots = [output + ".desktop.png", output + ".mobile.png"];
  for (const file of [output, ...screenshots]) if (fs.existsSync(file)) throw new Error("报告或截图已存在，请使用新文件名");
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const checks = [];
  const check = (name, condition = true) => { assert(condition, name); checks.push({ name, passed: true }); };
  let release = () => {}, browser;
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const page = await context.newPage();
    const pageErrors = []; page.on("pageerror", error => pageErrors.push(error.message));
    page.setDefaultTimeout(15000);
    const suffix = randomUUID().replaceAll("-", "").slice(0, 12);
    const first = "page_a_" + suffix, second = "page_b_" + suffix;
    const password = "browser-test-password";
    async function register(name) {
      await page.locator("#auth-name").fill(name);
      await page.locator("#auth-password").fill(password);
      await page.locator("#register").click();
      await page.waitForFunction(name => document.getElementById("username").textContent === name, name);
    }
    await page.goto(base);
    await register(first);
    check("实际后端注册并进入工作台");
    await page.getByRole("link", { name: "知识问答", exact: true }).click();
    await page.locator("#example").click();
    await page.locator("#submit-task").click();
    await page.waitForFunction(() => document.getElementById("result-status").textContent === "已完成");
    check("页面提交经过Java和真实Python返回离线结果", (await page.locator("#result-answer").textContent()).includes("未调用大模型"));
    const source = page.locator("#result-sources a").first();
    const sourceUrl = await source.getAttribute("href");
    assert(sourceUrl && sourceUrl.includes("/references/demo-408.html"));
    check("引用指向可访问的本项目演示原文", (await page.request.get(sourceUrl)).status() === 200);
    await page.getByRole("link", { name: "学习记录", exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll(".history-item").length === 1);
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll(".history-item").length === 1);
    check("页面刷新保持会话和真实任务历史");
    await page.getByRole("link", { name: "刷题中心", exact: true }).click();
    await page.locator("#practice-subject").selectOption("data_structure");
    await page.locator("#practice-count").fill("1");
    await page.locator("#practice-form button[type=submit]").click();
    await page.waitForFunction(() => document.querySelectorAll("#question-options input").length === 4);
    check("页面通过真实题库创建章节练习", await page.locator("#question-options input").count() === 4);
    await page.locator('#question-options input[value="A"]').check();
    await page.waitForFunction(() => document.getElementById("draft-state").textContent === "草稿已保存");
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll("#session-list .history-item").length === 1);
    await page.getByRole("button", { name: "继续练习" }).click();
    await page.waitForFunction(() => document.querySelectorAll("#question-options input").length === 4);
    check("刷新后恢复批次题序和答案草稿", await page.locator('#question-options input[value="A"]').isChecked());
    await page.locator("#hint-one").click();
    await page.waitForFunction(() => !document.getElementById("hint-content").hidden);
    await page.locator("#hint-two").click();
    await page.waitForFunction(() => document.getElementById("hint-content").textContent.length > 0);
    check("两级提示按顺序可用");
    await page.locator("#favorite-question").click();
    await page.waitForFunction(() => document.getElementById("favorite-question").textContent === "取消收藏");
    check("题目收藏状态保存");
    await page.locator("#submit-answer").click();
    await page.waitForFunction(() => !document.getElementById("practice-result").hidden);
    check("错答后自动完成单题批次并显示结果", (await page.locator("#result-metrics").textContent()).includes("答错"));
    await page.getByRole("link", { name: "错题本", exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll(".wrong-row").length === 1);
    check("错答自动归集到本人错题本");
    await page.locator("#start-wrong-practice").click();
    await page.waitForFunction(() => document.getElementById("practice-title").textContent === "错题重练");
    check("错题可以直接创建重练批次", (await page.locator("#practice-title").textContent()) === "错题重练");
    await page.screenshot({ path: screenshots[0], fullPage: true });
    check("学生页面不开放管理员入口", await page.locator("#admin-link").isHidden());

    let reached;
    const entered = new Promise(resolve => { reached = resolve; });
    const gate = new Promise(resolve => { release = resolve; });
    let held = false;
    await page.route("**/api/tasks", async route => {
      if (route.request().method() !== "POST" || held) return route.continue();
      held = true;
      const response = await route.fetch();
      reached(); await gate; await route.fulfill({ response });
    });
    await page.getByRole("link", { name: "知识问答", exact: true }).click();
    await page.locator("#task-input").fill("请解释TCP可靠传输的概念。");
    await page.locator("#submit-task").click();
    await Promise.race([entered, new Promise((_, reject) => setTimeout(() => reject(new Error("迟到请求未进入测试拦截")), 15000))]);
    await page.locator("#logout").click();
    await register(second);
    const delayedResponse = page.waitForResponse(response => response.url().endsWith("/api/tasks") && response.request().method() === "POST");
    release(); await delayedResponse;
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    check("换账号后忽略上一账号的迟到响应", !(await page.locator("#result-answer").textContent()).includes("可靠传输"));
    await page.getByRole("link", { name: "学习记录", exact: true }).click();
    check("新账号历史保持隔离", await page.locator(".history-item").count() === 0);
    const token = await page.evaluate(() => sessionStorage.getItem("kaoyan_token"));
    const headers = { Authorization: `Bearer ${token}` };
    const newAccountWrong = await page.request.get(base + "/api/wrong-questions?page=0", { headers });
    check("新账号看不到原账号错题", newAccountWrong.ok() && (await newAccountWrong.json()).totalItems === 0);
    check("未实现档案接口返回501", (await page.request.get(base + "/api/profile", { headers })).status() === 501);
    check("服务端拒绝学生访问管理接口", (await page.request.get(base + "/api/admin/documents", { headers })).status() === 403);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("link", { name: "刷题中心", exact: true }).click();
    check("390宽度没有横向溢出", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: screenshots[1], fullPage: true });
    check("无页面脚本异常", pageErrors.length === 0);
    await page.locator("#logout").click();
    await page.locator("#auth-name").fill(first);
    await page.locator("#auth-password").fill(password);
    await page.locator("#login").click();
    await page.waitForFunction(name => document.getElementById("username").textContent === name, first);
    check("已有账号可以重新登录");
    await context.close();
  } finally { release(); if (browser) await browser.close(); }
  fs.writeFileSync(output, JSON.stringify({ scope: "实际Java/Python后端、独立浏览器上下文、工程演示；390宽度不是实机手机", checks, screenshots }, null, 2), { flag: "wx" });
  console.log(`通过 ${checks.length} 项页面检查；隔离浏览器已关闭。`);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
